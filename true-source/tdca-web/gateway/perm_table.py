ALLOW_VALUES = ("yes", "no", "yes-require-signature", "na")


def _allow_of(marks: str) -> str:
    """记号 → 四值之一（恒规：❌ 优先 fail-closed；✍️ 须签；— 不适用）。"""
    if "❌" in marks:
        return "no"
    if marks.strip() == "—":
        return "na"
    if "✍️" in marks:
        return "yes-require-signature"
    if "✅" in marks:
        return "yes"
    raise ValueError(f"未知记号: {marks!r}")


def _basis(dom: str, act: str, col: str) -> str:
    b = _B.get((dom, act, col))
    if b is None:
        # 仅 na 格允许走统一口径；其余漏写即 fail-closed 报错（S-4 不缺一条）
        marks = GRID[dom]["rows"][act][GRID[dom]["columns"].index(col)]
        if _allow_of(marks) == "na":
            return _NA_BASIS
        raise KeyError(f"权限点表缺 basis: {dom}/{act}/{col}")
    return b


def build_permissions(role: str) -> dict:
    """由权限点表直接生成本人权限清单（role 沿用既有三值枚举）。"""
    cols = _ROLE_COLUMNS.get(role)
    if cols is None:
        raise ValueError(f"未知角色: {role!r}")
    matrix = []
    for dom, col in cols.items():
        g = GRID[dom]
        for act, marks_row in g["rows"].items():
            marks = marks_row[g["columns"].index(col)]
            matrix.append({"action": act, "on": dom, "allow": _allow_of(marks),
                           "basis": _basis(dom, act, col)})
    return {"role": role, "scopes": list(_SCOPES[role]), "matrix": matrix,
            "note": _NOTE[role], "scope": "self"}
